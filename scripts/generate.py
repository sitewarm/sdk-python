"""Regenerates src/sitewarm/_generated/* from the vendored spec (openapi/openapi.yaml).

- models.py     : pydantic v2 models from datamodel-code-generator
- operations.py : operationId -> method/path/idempotency table used by the runtime client

CI runs this and fails on drift (git diff of src/sitewarm/_generated).
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "openapi" / "openapi.yaml"
OUT = ROOT / "src" / "sitewarm" / "_generated"
BANNER = "# GENERATED by scripts/generate.py from openapi/openapi.yaml. Do not edit.\n"

OUT.mkdir(parents=True, exist_ok=True)
(OUT / "__init__.py").write_text(BANNER)

subprocess.run(
    [
        sys.executable, "-m", "datamodel_code_generator",
        "--input", str(SPEC),
        "--input-file-type", "openapi",
        "--output", str(OUT / "models.py"),
        "--output-model-type", "pydantic_v2.BaseModel",
        "--target-python-version", "3.10",
        "--use-annotated",
        "--use-standard-collections",
        "--use-union-operator",
        "--disable-timestamp",
        "--custom-file-header", BANNER.rstrip("\n"),
    ],
    check=True,
)

spec = yaml.safe_load(SPEC.read_text())
rows = []
for path, item in spec["paths"].items():
    for method in ("get", "put", "post", "patch", "delete"):
        op = item.get(method)
        if not op:
            continue
        refs = [p.get("$ref", "") for p in [*item.get("parameters", []), *op.get("parameters", [])]]
        idem = next((r for r in refs if r.endswith("/IdempotencyKey") or r.endswith("/IdempotencyKeyRequired")), None)
        kind = "none" if not idem else ("required" if idem.endswith("Required") else "optional")
        rows.append(f'    "{op["operationId"]}": Operation("{method.upper()}", "{path}", "{kind}"),')

(OUT / "operations.py").write_text(
    BANNER
    + "from __future__ import annotations\n\nfrom typing import NamedTuple\n\n\n"
    + "class Operation(NamedTuple):\n    method: str\n    path: str\n    idempotency: str  # none | optional | required\n\n\n"
    + "OPERATIONS: dict[str, Operation] = {\n"
    + "\n".join(rows)
    + "\n}\n"
)
print(f"generated {len(rows)} operations")
